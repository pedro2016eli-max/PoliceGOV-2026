DROP TABLE IF EXISTS ficha_inquerito CASCADE;
DROP TABLE IF EXISTS bo_cidadao CASCADE;
DROP TABLE IF EXISTS bo_tipo CASCADE;
DROP TABLE IF EXISTS bo CASCADE;
