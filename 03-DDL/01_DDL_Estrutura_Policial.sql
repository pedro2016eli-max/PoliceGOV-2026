-- 2. TABELA DELEGACIA

CREATE TABLE delegacia (
    id_delegacia INT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    municipio VARCHAR(60) NOT NULL,
    logradouro VARCHAR(100) NOT NULL,
    numero INT NOT NULL,
    bairro VARCHAR(60) NOT NULL,
    cep CHAR(8) NOT NULL,
    cidade VARCHAR(60) NOT NULL,

    CONSTRAINT pk_delegacia
        PRIMARY KEY (id_delegacia),

    CONSTRAINT uq_delegacia_nome
        UNIQUE (nome),

    CONSTRAINT ck_delegacia_numero
        CHECK (numero > 0),

    CONSTRAINT ck_delegacia_cep
        CHECK (cep ~ '^[0-9]{8}$')
);

-- 3. TABELA DELEGACIA_TELEFONE

CREATE TABLE delegacia_telefone (
    id_delegacia INT NOT NULL,
    telefone VARCHAR(11) NOT NULL,

    CONSTRAINT pk_delegacia_telefone
        PRIMARY KEY (id_delegacia, telefone),

    CONSTRAINT fk_telefone_delegacia
        FOREIGN KEY (id_delegacia)
        REFERENCES delegacia (id_delegacia)
        ON DELETE CASCADE
        ON UPDATE RESTRICT,

    CONSTRAINT ck_telefone_formato
        CHECK (telefone ~ '^[0-9]{10,11}$')
);

-- 4. TABELA POLICIAL

CREATE TABLE policial (
    matricula VARCHAR(10) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    cargo VARCHAR(30) NOT NULL,
    id_delegacia INT NOT NULL,

    CONSTRAINT pk_policial
        PRIMARY KEY (matricula),

    CONSTRAINT uq_policial_email
        UNIQUE (email),

    CONSTRAINT uq_policial_matricula_cargo
        UNIQUE (matricula, cargo),

    CONSTRAINT fk_policial_delegacia
        FOREIGN KEY (id_delegacia)
        REFERENCES delegacia (id_delegacia)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_policial_cargo
        CHECK (cargo IN (
            'Delegado de Polícia',
            'Investigador',
            'Escrivão'
        )),

    CONSTRAINT ck_policial_email
        CHECK (email LIKE '%_@_%._%'),

    CONSTRAINT ck_policial_matricula
        CHECK (matricula ~ '^[0-9]{6,10}$')
);

-- 5. TABELA DELEGADO

CREATE TABLE delegado (
    matricula VARCHAR(10) NOT NULL,
    cargo VARCHAR(30) NOT NULL
        DEFAULT 'Delegado de Polícia',
    numero_portaria VARCHAR(20) NOT NULL,

    CONSTRAINT pk_delegado
        PRIMARY KEY (matricula),

    CONSTRAINT uq_delegado_portaria
        UNIQUE (numero_portaria),

    CONSTRAINT fk_delegado_policial
        FOREIGN KEY (matricula, cargo)
        REFERENCES policial (matricula, cargo)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_delegado_cargo
        CHECK (cargo = 'Delegado de Polícia')
);

-- 6. TABELA INVESTIGADOR_ESCRIVAO

CREATE TABLE investigador_escrivao (
    matricula VARCHAR(10) NOT NULL,
    cargo VARCHAR(30) NOT NULL,
    area_atuacao VARCHAR(80) NOT NULL,

    CONSTRAINT pk_investigador_escrivao
        PRIMARY KEY (matricula),

    CONSTRAINT fk_inv_esc_policial
        FOREIGN KEY (matricula, cargo)
        REFERENCES policial (matricula, cargo)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_inv_esc_cargo
        CHECK (cargo IN (
            'Investigador',
            'Escrivão'
        ))
);

-- 7. CONFERENCIA DAS TABELAS CRIADAS

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;
